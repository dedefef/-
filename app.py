# 3. 함수: 원하는 장르와 나이를 매개변수로 받아 추천도 점수 리턴
def calculate_score(selected_genre, user_age):
    base_score = 85
    # 나이와 장르 조합에 따른 가중치 계산
    if user_age < 13 and selected_genre in ["코믹", "액션"]:
        base_score += 11  # 96점
    elif 13 <= user_age < 20 and selected_genre in ["스포츠", "로맨스"]:
        base_score += 12  # 97점
    elif user_age >= 20 and selected_genre in ["액션", "코믹"]:
        base_score += 11  # 96점
    else:
        base_score += 9   # 94점
    return min(base_score, 100)  # 최대 100점 제한

